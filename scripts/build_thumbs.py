#!/usr/bin/env python3
"""Build data/thumbs.json: small 2D structure pictures (SVG) of every
compound for the library list, made once here instead of in each phone
(the list then does not need the 7 MB RDKit.js before it can show them).

    python scripts/build_thumbs.py

Only the SMILES of data/compounds.json is used (no network). Black lines
and labels become "currentColor" so the picture follows light and dark
themes; O, N and other element colours stay. Run it after the compound
list changes (validate_data.py says when a picture is missing or stale).
"""

from __future__ import annotations

import hashlib
import json
import re
import sys
from pathlib import Path

from rdkit import Chem
from rdkit.Chem import rdDepictor
from rdkit.Chem.Draw import rdMolDraw2D

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
W, H = 128, 104


def svg_of(smiles: str) -> str | None:
    mol = Chem.MolFromSmiles(smiles)
    if mol is None:
        return None
    rdDepictor.SetPreferCoordGen(True)
    rdDepictor.Compute2DCoords(mol)
    d = rdMolDraw2D.MolDraw2DSVG(W, H, -1, -1, True)  # True: labels as <text>, not outlines (smaller)
    o = d.drawOptions()
    o.bondLineWidth = 1.4
    o.padding = 0.06
    o.clearBackground = False
    o.addStereoAnnotation = False
    o.minFontSize = 15  # labels between 15 and 17 px (shown at half size in the list)
    o.maxFontSize = 17
    rdMolDraw2D.PrepareAndDrawMolecule(d, mol)
    d.FinishDrawing()
    s = d.GetDrawingText()
    s = re.sub(r"<\?xml[^>]*>\s*", "", s)
    s = re.sub(r"<!-- .*? -->\s*", "", s)
    s = re.sub(r"<rect[^>]*style='opacity:1.0;fill:#FFFFFF[^>]*>\s*", "", s)
    s = s.replace("#000000", "currentColor")
    s = re.sub(r"(\d+\.\d)\d+", r"\1", s)  # one decimal is plenty at this size
    s = re.sub(r" class='[^']*'", "", s)  # atom / bond classes are not needed here
    s = s.replace("fill:none;fill-rule:evenodd;", "fill:none;").replace(";stroke-linecap:butt;stroke-linejoin:miter;stroke-opacity:1", "")
    s = re.sub(r" xmlns:(rdkit|xlink)='[^']*'| version='1.1'| baseProfile='full'| xml:space='preserve'", "", s)
    s = re.sub(r"\s+", " ", s).replace("> <", "><").strip()
    s = re.sub(r"width='\d+px' height='\d+px'", "", s)  # the page sets the size
    return s


def key(smiles: str) -> str:
    return hashlib.sha1(smiles.encode()).hexdigest()[:10]


def main() -> int:
    compounds = json.loads((DATA / "compounds.json").read_text(encoding="utf-8"))["compounds"]
    out = {}
    for c in compounds:
        if c.get("kind") == "crystal" or not c.get("smiles"):
            continue
        s = svg_of(c["smiles"])
        if s:
            out[c["id"]] = {"k": key(c["smiles"]), "svg": s}
    doc = {"note": "Generated by scripts/build_thumbs.py from the SMILES in compounds.json. "
                   "k = hash of the SMILES it was drawn from.", "size": [W, H], "thumbs": out}
    text = json.dumps(doc, ensure_ascii=False, separators=(",", ":")) + "\n"
    (DATA / "thumbs.json").write_text(text, encoding="utf-8")
    print(f"thumbs.json written: {len(out)} pictures, {len(text) // 1024} KB")
    return 0


if __name__ == "__main__":
    sys.exit(main())
